"""Escribe un programa que declare la variable año = 2001 y ejecute un bucle while mientras año <= 2017 .
En cada iteración debe imprimir: "Informes del Año [año]" e incrementar la variable en 1.
Incluye la sentencia opcional else al final del bucle while para imprimir "Hemos terminado" al finalizar la
condición."""

año=2001

while año <= 2017:
    print("Informes del Año", año)
    año=año+1

print("hemos terminado")