# 01 - Crear diccionarios
# Una clave identifica a su valor.

# Diccionario con datos
alumno = {
    "nombre": "Lucia",
    "edad": 20,
    "nota": 8.5
}

print(alumno)

# Diccionario vacío
agenda = {}

# Las claves pueden ser de distintos tipos inmutables
precios = {
    "pan": 1.20,
    "leche": 0.95,
    100: "codigo numerico"
}

print(precios)
