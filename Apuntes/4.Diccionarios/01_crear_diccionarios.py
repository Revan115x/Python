# CREAR DICCIONARIOS

# Con llaves
capitales = {
    "Francia": "París",
    "Italia": "Roma",
    "España": "Madrid"
}
print(capitales)

# Con dict()
persona = dict(nombre="Ana", edad=20)
print(persona)

# Diccionario vacío
vacio1 = {}
vacio2 = dict()

# Convertir una lista de tuplas
parejas = [("a", 1), ("b", 2), ("c", 3)]
tabla = dict(parejas)
print(tabla)
