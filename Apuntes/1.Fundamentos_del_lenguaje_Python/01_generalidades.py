# 01 - Generalidades de Python
# Practica: instrucciones, indentacion, continuacion de linea y comentarios.

# Una instruccion por linea (forma recomendada).
nombre = "Ana"
edad = 20

# Varias instrucciones en una linea son posibles, pero no se recomiendan.
a = 3; b = 4

# La indentacion indica que estas instrucciones pertenecen al if.
if edad >= 18:
    print("Mayor de edad")
    print("Puede acceder")

# Una expresion puede continuar dentro de parentesis.
total = (
    10 + 20
    + 30
)

# Comentario de una linea.
print("Nombre:", nombre)
print("Total:", total)
