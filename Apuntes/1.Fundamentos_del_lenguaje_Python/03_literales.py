# 03 - Literales numericos y cadenas

# Enteros
entero = 12
negativo = -23
binario = 0b10101
octal = 0o377
hexadecimal = 0xff

# Reales: Python utiliza punto decimal.
precio = 12.3
pequeno = 0.001
cientifico = 3.14e-10

# Numero complejo
complejo = 1 + 2j

# Cadenas con comillas simples o dobles
nombre = 'Lucia'
saludo = "Hola"

# Secuencias de escape
texto = "Primera linea\nSegunda linea"
tabulacion = "Nombre:\tAna"
comilla = "Me dijo: \"Hola\""

print(entero, negativo, binario, octal, hexadecimal)
print(precio, pequeno, cientifico, complejo)
print(texto)
print(tabulacion)
print(comilla)
